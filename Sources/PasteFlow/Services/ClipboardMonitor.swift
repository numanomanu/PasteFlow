import Foundation
import AppKit

@MainActor
public final class ClipboardMonitor: ObservableObject {
    public static let shared = ClipboardMonitor()

    private var timer: Timer?
    private var lastChangeCount: Int = 0
    private var isSuppressed: Bool = false
    
    // Concealed / Transient types to ignore (passwords, auto-fills)
    private let ignoredTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("com.lastpass.LastPass")
    ]

    private init() {
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    public func startMonitoring(interval: TimeInterval = 0.35) {
        stopMonitoring()
        self.lastChangeCount = NSPasteboard.general.changeCount
        
        let t = Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkForChanges()
            }
        }
        // Allow timer coalescing to optimize power/battery usage
        t.tolerance = 0.1
        timer = t
    }

    public func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    /// Suppress recording next change (used when PasteFlow itself writes to pasteboard)
    public func suppressNextRecording() {
        isSuppressed = true
    }

    private func checkForChanges() {
        let pasteboard = NSPasteboard.general
        let currentChangeCount = pasteboard.changeCount

        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount

        if isSuppressed {
            isSuppressed = false
            return
        }

        // Check for concealed or transient types
        guard let types = pasteboard.types else { return }
        for ignored in ignoredTypes {
            if types.contains(ignored) {
                return
            }
        }

        // Retrieve frontmost app as source
        let frontApp = NSWorkspace.shared.frontmostApplication
        let appName = frontApp?.localizedName
        let bundleId = frontApp?.bundleIdentifier

        // 1. Check for File URLs first (prevents Finder file copies from being captured as icon TIFF images)
        if types.contains(.fileURL) || types.contains(NSPasteboard.PasteboardType("public.file-url")) {
            if let fileUrls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL], !fileUrls.isEmpty {
                let paths = fileUrls.filter { $0.isFileURL }.map { $0.absoluteString }
                if !paths.isEmpty {
                    let firstPath = fileUrls.first?.path ?? ""
                    let item = ClipItem(
                        type: .file,
                        plainText: firstPath,
                        fileURLs: paths,
                        sourceAppName: appName,
                        sourceAppBundleId: bundleId
                    )
                    HistoryStore.shared.add(item: item)
                    return
                }
            }
        }

        // 2. Check for Image (only when not a file copy)
        if types.contains(.tiff) || types.contains(.png) {
            if let image = NSImage(pasteboard: pasteboard) {
                if let saved = HistoryStore.shared.saveImage(image) {
                    let item = ClipItem(
                        type: .image,
                        imageFileName: saved.fileName,
                        imageWidth: saved.width,
                        imageHeight: saved.height,
                        sourceAppName: appName,
                        sourceAppBundleId: bundleId
                    )
                    HistoryStore.shared.add(item: item)
                    return
                }
            }
        }

        // 3. Check for String / Text
        if let string = pasteboard.string(forType: .string), !string.isEmpty {
            // Guard against excessively large text copies (e.g. dumps, huge log files > 200,000 chars)
            // to protect memory and prevent freezing.
            let maxCharacters = 200_000
            if string.count > maxCharacters {
                print("Skipped copying excessively large text (\(string.count) characters).")
                return
            }

            var clipType: ClipType = .text
            var detectedHex: String? = nil

            if let hex = ClipItem.detectColor(from: string) {
                clipType = .color
                detectedHex = hex
            } else if ClipItem.isURL(string) {
                clipType = .link
            }

            // Retrieve RTF & HTML data with fallbacks (Slack, Confluence, Chrome, Safari)
            var rtfData = pasteboard.data(forType: .rtf)
            if rtfData == nil {
                rtfData = pasteboard.data(forType: NSPasteboard.PasteboardType("public.rtf"))
            }

            var html = pasteboard.string(forType: .html)
            if (html == nil || html?.isEmpty == true), let htmlData = pasteboard.data(forType: .html) {
                html = String(data: htmlData, encoding: .utf8) ?? String(data: htmlData, encoding: .ascii)
            }

            // Memory guard: skip rich data if larger than 500 KB to avoid excessive memory consumption
            let maxRichBytes = 500_000
            if let rtf = rtfData, rtf.count > maxRichBytes {
                rtfData = nil
            }
            if let h = html, h.utf8.count > maxRichBytes {
                html = nil
            }

            let item = ClipItem(
                type: clipType,
                plainText: string,
                richTextRTF: rtfData,
                htmlContent: html,
                sourceAppName: appName,
                sourceAppBundleId: bundleId,
                colorHex: detectedHex
            )
            HistoryStore.shared.add(item: item)
            return
        }
    }
}
